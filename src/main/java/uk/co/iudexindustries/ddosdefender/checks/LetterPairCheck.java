    public int score(String name) {
        if (name == null) return 0;
        int sum = 0, pairs = 0, prev = -1;
        for (int i = 0; i < name.length(); i++) {
            char c = name.charAt(i);
            int letter = (c >= 'a' && c <= 'z') ? c - 'a' : (c >= 'A' && c <= 'Z') ? c - 'A' : -1;
            if (letter >= 0 && prev >= 0) {
                sum += COST[prev * 26 + letter];
                pairs++;
            }
            prev = letter;
        }
        if (pairs < 4) return 0;
        int avg = sum / pairs; // tenths of a bit
        if (avg >= 68) return 40;
        if (avg >= 60) return 28;
        if (avg >= 52) return 15;
        return 0;
    }
